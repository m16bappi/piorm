use std::path::Path;

use piorm_core::backend::QueryBackend;
use piorm_core::pool::PiormPool;
use sqlx::Row;

#[derive(clap::Args)]
pub struct InspectdbArgs {
    /// Specific table names to inspect (default: all)
    pub tables: Vec<String>,

    /// Include views in output
    #[arg(long)]
    pub include_views: bool,
}

struct TableInfo {
    name: String,
    columns: Vec<ColumnInfo>,
}

struct ColumnInfo {
    name: String,
    type_str: String,
    not_null: bool,
    pk: bool,
}

pub async fn run_inspectdb(
    args: InspectdbArgs,
    pool: PiormPool,
    _migrations_dir: &Path,
) -> piorm_core::Result<i32> {
    let _backend = QueryBackend(pool.backend());
    let tables = introspect_schema(&pool, &args.tables, args.include_views).await?;

    println!("# This file was auto-generated by 'piorm inspectdb'.");
    println!("# You'll have to do the following manually:");
    println!("#   * Rearrange models' order");
    println!("#   * Make sure each model has one field with primary_key=True");
    println!("from piorm import Model, CharField, IntegerField, BigIntegerField, ForeignKey, CASCADE");
    println!("from piorm import TextField, BooleanField, DateTimeField, FloatField, DecimalField");
    println!("from piorm import DateField, TimeField, UUIDField, JSONField, BinaryField");
    println!();

    for table in &tables {
        let class_name = snake_to_pascal(&table.name);
        println!("class {}(Model):", class_name);
        if table.columns.is_empty() {
            println!("    pass");
        } else {
            for col in &table.columns {
                let field = column_to_field(col);
                println!("    {} = {}", col.name, field);
            }
        }
        println!();
        println!("    class Meta:");
        println!("        db_table = '{}'", table.name);
        println!("        managed = False  # or True if you want piorm to manage this table");
        println!();
    }

    Ok(0)
}

async fn introspect_schema(
    pool: &PiormPool,
    filter: &[String],
    include_views: bool,
) -> piorm_core::Result<Vec<TableInfo>> {
    match pool {
        PiormPool::Sqlite(p) => {
            let type_filter = if include_views {
                "type IN ('table', 'view')"
            } else {
                "type = 'table'"
            };
            let sql = format!(
                "SELECT name FROM sqlite_master WHERE {} AND name NOT LIKE 'sqlite_%' ORDER BY name",
                type_filter
            );
            let rows = sqlx::query(&sql)
                .fetch_all(p)
                .await
                .map_err(piorm_core::PiormError::Database)?;

            let mut tables = Vec::new();
            for row in rows {
                let name: String = row.get("name");
                if !filter.is_empty() && !filter.contains(&name) {
                    continue;
                }

                let col_rows = sqlx::query(&format!("PRAGMA table_info(\"{}\")", name))
                    .fetch_all(p)
                    .await
                    .map_err(piorm_core::PiormError::Database)?;

                let columns = col_rows
                    .iter()
                    .map(|c| ColumnInfo {
                        name: c.get::<String, _>("name"),
                        type_str: c.get::<String, _>("type"),
                        not_null: c.get::<i32, _>("notnull") != 0,
                        pk: c.get::<i32, _>("pk") != 0,
                    })
                    .collect();

                tables.push(TableInfo { name, columns });
            }
            Ok(tables)
        }
        PiormPool::Postgres(p) => {
            let table_type = if include_views { "'BASE TABLE','VIEW'" } else { "'BASE TABLE'" };
            let sql = format!(
                "SELECT table_name FROM information_schema.tables \
                 WHERE table_schema = 'public' AND table_type IN ({}) \
                 ORDER BY table_name",
                table_type
            );
            let rows = sqlx::query(&sql)
                .fetch_all(p)
                .await
                .map_err(piorm_core::PiormError::Database)?;

            let mut tables = Vec::new();
            for row in rows {
                let name: String = row.get("table_name");
                if !filter.is_empty() && !filter.contains(&name) {
                    continue;
                }

                let col_sql = "SELECT column_name, data_type, is_nullable, \
                               (SELECT COUNT(*) FROM information_schema.table_constraints tc \
                                JOIN information_schema.key_column_usage kcu \
                                  ON tc.constraint_name = kcu.constraint_name \
                                WHERE tc.constraint_type = 'PRIMARY KEY' \
                                  AND kcu.table_name = $1 \
                                  AND kcu.column_name = c.column_name) > 0 AS is_pk \
                               FROM information_schema.columns c \
                               WHERE table_schema = 'public' AND table_name = $1 \
                               ORDER BY ordinal_position";

                let col_rows = sqlx::query(col_sql)
                    .bind(&name)
                    .fetch_all(p)
                    .await
                    .map_err(piorm_core::PiormError::Database)?;

                let columns = col_rows
                    .iter()
                    .map(|c| ColumnInfo {
                        name: c.get::<String, _>("column_name"),
                        type_str: c.get::<String, _>("data_type"),
                        not_null: c.get::<String, _>("is_nullable") == "NO",
                        pk: c.get::<bool, _>("is_pk"),
                    })
                    .collect();

                tables.push(TableInfo { name, columns });
            }
            Ok(tables)
        }
        PiormPool::Mysql(p) => {
            let sql = if include_views {
                "SELECT table_name FROM information_schema.tables \
                 WHERE table_schema = DATABASE() ORDER BY table_name".to_string()
            } else {
                "SELECT table_name FROM information_schema.tables \
                 WHERE table_schema = DATABASE() AND table_type = 'BASE TABLE' \
                 ORDER BY table_name".to_string()
            };
            let rows = sqlx::query(&sql)
                .fetch_all(p)
                .await
                .map_err(piorm_core::PiormError::Database)?;

            let mut tables = Vec::new();
            for row in rows {
                let name: String = row.get("table_name");
                if !filter.is_empty() && !filter.contains(&name) {
                    continue;
                }

                let col_sql = "SELECT column_name, data_type, is_nullable, \
                               (column_key = 'PRI') AS is_pk \
                               FROM information_schema.columns \
                               WHERE table_schema = DATABASE() AND table_name = ? \
                               ORDER BY ordinal_position";

                let col_rows = sqlx::query(col_sql)
                    .bind(&name)
                    .fetch_all(p)
                    .await
                    .map_err(piorm_core::PiormError::Database)?;

                let columns = col_rows
                    .iter()
                    .map(|c| ColumnInfo {
                        name: c.get::<String, _>("column_name"),
                        type_str: c.get::<String, _>("data_type"),
                        not_null: c.get::<String, _>("is_nullable") == "NO",
                        pk: c.get::<i8, _>("is_pk") != 0,
                    })
                    .collect();

                tables.push(TableInfo { name, columns });
            }
            Ok(tables)
        }
    }
}

fn column_to_field(col: &ColumnInfo) -> String {
    let type_upper = col.type_str.to_uppercase();
    let mut kwargs: Vec<String> = Vec::new();

    if col.pk {
        kwargs.push("primary_key=True".to_string());
    } else if !col.not_null {
        kwargs.push("null=True".to_string());
        kwargs.push("blank=True".to_string());
    }

    let field_class = if type_upper.starts_with("VARCHAR") || type_upper.starts_with("CHARACTER VARYING") {
        let max_len = extract_size(&type_upper).unwrap_or(255);
        kwargs.push(format!("max_length={}", max_len));
        "CharField"
    } else if type_upper.starts_with("DECIMAL") || type_upper.starts_with("NUMERIC") {
        let (p, s) = extract_precision(&type_upper).unwrap_or((10, 2));
        kwargs.push(format!("max_digits={}", p));
        kwargs.push(format!("decimal_places={}", s));
        "DecimalField"
    } else {
        match type_upper.as_str() {
            "TEXT" | "CLOB" | "MEDIUMTEXT" | "LONGTEXT" => "TextField",
            "INTEGER" | "INT" | "INT4" | "MEDIUMINT" => "IntegerField",
            "BIGINT" | "INT8" | "BIGSERIAL" => "BigIntegerField",
            "SMALLINT" | "INT2" | "TINYINT" => "SmallIntegerField",
            "SERIAL" | "AUTOINCREMENT" => "AutoField",
            "REAL" | "FLOAT" | "FLOAT4" | "FLOAT8" | "DOUBLE" | "DOUBLE PRECISION" => "FloatField",
            "BOOLEAN" | "BOOL" | "BIT" => "BooleanField",
            "DATE" => "DateField",
            "TIME" | "TIME WITHOUT TIME ZONE" | "TIME WITH TIME ZONE" => "TimeField",
            "DATETIME" | "TIMESTAMP" | "TIMESTAMP WITHOUT TIME ZONE" | "TIMESTAMP WITH TIME ZONE" => "DateTimeField",
            "UUID" => "UUIDField",
            "JSON" | "JSONB" => "JSONField",
            "BLOB" | "BYTEA" | "BINARY" | "VARBINARY" => "BinaryField",
            "CHAR" => {
                kwargs.push("max_length=1".to_string());
                "CharField"
            }
            _ => "TextField",
        }
    };

    if kwargs.is_empty() {
        format!("{}()", field_class)
    } else {
        format!("{}({})", field_class, kwargs.join(", "))
    }
}

fn snake_to_pascal(s: &str) -> String {
    s.split('_')
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
            }
        })
        .collect()
}

fn extract_size(type_str: &str) -> Option<u32> {
    let start = type_str.find('(')?;
    let end = type_str.find(')')?;
    type_str[start + 1..end].trim().parse().ok()
}

fn extract_precision(type_str: &str) -> Option<(u32, u32)> {
    let start = type_str.find('(')?;
    let end = type_str.find(')')?;
    let inner = &type_str[start + 1..end];
    let mut parts = inner.split(',');
    let p: u32 = parts.next()?.trim().parse().ok()?;
    let s: u32 = parts.next()?.trim().parse().ok()?;
    Some((p, s))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_snake_to_pascal() {
        assert_eq!(snake_to_pascal("blog_post"), "BlogPost");
        assert_eq!(snake_to_pascal("user"), "User");
        assert_eq!(snake_to_pascal("auth_user_group"), "AuthUserGroup");
    }

    #[test]
    fn test_column_to_field_text() {
        let col = ColumnInfo { name: "body".into(), type_str: "TEXT".into(), not_null: false, pk: false };
        assert_eq!(column_to_field(&col), "TextField(null=True, blank=True)");
    }

    #[test]
    fn test_column_to_field_varchar() {
        let col = ColumnInfo { name: "title".into(), type_str: "VARCHAR(200)".into(), not_null: true, pk: false };
        assert_eq!(column_to_field(&col), "CharField(max_length=200)");
    }

    #[test]
    fn test_column_to_field_pk() {
        let col = ColumnInfo { name: "id".into(), type_str: "INTEGER".into(), not_null: true, pk: true };
        assert_eq!(column_to_field(&col), "IntegerField(primary_key=True)");
    }

    #[test]
    fn test_column_to_field_bool() {
        let col = ColumnInfo { name: "active".into(), type_str: "BOOLEAN".into(), not_null: true, pk: false };
        assert_eq!(column_to_field(&col), "BooleanField()");
    }

    #[test]
    fn test_extract_size() {
        assert_eq!(extract_size("VARCHAR(200)"), Some(200));
        assert_eq!(extract_size("TEXT"), None);
    }

    #[test]
    fn test_extract_precision() {
        assert_eq!(extract_precision("DECIMAL(10, 2)"), Some((10, 2)));
        assert_eq!(extract_precision("NUMERIC(15,4)"), Some((15, 4)));
    }

    #[tokio::test]
    async fn test_inspectdb_sqlite() {
        // Create an in-memory SQLite with some tables
        let pool = sqlx::sqlite::SqlitePoolOptions::new()
            .max_connections(1)
            .connect(":memory:")
            .await
            .unwrap();

        sqlx::query(
            "CREATE TABLE users (id INTEGER PRIMARY KEY, name VARCHAR(100) NOT NULL, email TEXT)"
        )
        .execute(&pool)
        .await
        .unwrap();

        let piorm_pool = piorm_core::pool::PiormPool::Sqlite(pool);
        let tables = introspect_schema(&piorm_pool, &[], false).await.unwrap();

        // Filter out sqlite internal tables
        let user_table = tables.iter().find(|t| t.name == "users").expect("users table");
        assert_eq!(user_table.columns.len(), 3);
        assert_eq!(user_table.columns[0].name, "id");
        assert!(user_table.columns[0].pk);
        assert_eq!(user_table.columns[1].name, "name");
        assert!(user_table.columns[1].not_null);
    }
}
